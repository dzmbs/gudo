import PackageDescription

// Decryption for the Notification Service Extension (and the Live Activity widget): opens the
// HPKE-sealed, daemon-signed payloads that crates/push produces. CryptoKit only, no app
// dependencies, so the extension stays small. See docs/PUSH.md.
let package = Package(
    name: "PushCrypto",
    platforms: [.macOS(.v26), .iOS(.v26)],
    products: [
        .library(name: "PushCrypto", targets: ["PushCrypto"]),
    ],
    targets: [
        .target(name: "PushCrypto"),
        .testTarget(
            name: "PushCryptoTests",
            dependencies: ["PushCrypto"],
            // push-v1.json is generated by crates/push/tests/vectors.rs (byte-identical copy).
            resources: [.copy("Resources/push-v1.json")]
        ),
    ]
)
