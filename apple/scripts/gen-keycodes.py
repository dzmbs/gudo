#!/usr/bin/env python3
"""Generate TerminalCore/KeyCodes.swift from Ghostty's src/input/keycodes.zig.

The table maps USB HID usages (UIKit `UIKey.keyCode`, page 0x07) and macOS virtual keycodes
(`NSEvent.keyCode`) to libghostty-vt's `GhosttyKey`, so the AppKit and UIKit hosts share one table.
Re-run after bumping vendor/ghostty:  python3 apple/scripts/gen-keycodes.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
zig = (root / "vendor/ghostty/src/input/keycodes.zig").read_text()
header = (root / "vendor/ghostty/include/ghostty/vt/key/event.h").read_text()
out = root / "apple/Packages/TerminalKit/Sources/TerminalCore/KeyCodes.swift"

code_to_tag = dict(re.findall(r'\.\{ "(\w+)", \.(\w+) \}', zig))
known = set(re.findall(r"\b(GHOSTTY_KEY_[A-Z0-9_]+)\b", header))
rows = re.findall(
    r"\.\{ (0x[0-9a-f]+), 0x[0-9a-f]+, 0x[0-9a-f]+, 0x[0-9a-f]+, (0x[0-9a-f]+), \"(\w+)\" \}", zig
)


def ghostty_name(tag: str) -> str:
    tag = tag[len("key_"):] if tag.startswith("key_") and len(tag) == 5 else tag
    return "GHOSTTY_KEY_" + tag.upper()


entries = []
for usb, mac, code in rows:
    tag = code_to_tag.get(code)
    if tag is None:
        continue
    name = ghostty_name(tag)
    if name not in known:
        raise SystemExit(f"unknown key {name} for code {code}")
    entries.append((int(usb, 16), int(mac, 16), name, code))

lines = [
    "// Generated by apple/scripts/gen-keycodes.py from vendor/ghostty/src/input/keycodes.zig",
    "// (Chromium dom_code_data.inc, BSD-style license). Do not edit by hand.",
    "import CGhosttyVt",
    "",
    "/// (USB HID usage, macOS virtual keycode or 0xFFFF, libghostty-vt key)",
    "let keyCodeTable: [(usb: UInt32, mac: UInt16, key: GhosttyKey)] = [",
]
for usb, mac, name, code in entries:
    lines.append(f"    (0x{usb:06x}, 0x{mac:04x}, {name}),  // {code}")
lines.append("]")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {len(entries)} entries to {out.relative_to(root)}")
