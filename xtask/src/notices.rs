//! `cargo xtask notices [--check]`: the licence notices that ship with our binaries.
//!
//! - `crates/hostd/THIRD_PARTY_NOTICES.txt`, embedded in the helper (`gudo-hostd
//!   licenses`): the native code it links (`scripts/notices/native.txt`, kept by hand) and its
//!   Rust crates.
//! - `apple/App/Resources/THIRD_PARTY_NOTICES.txt`, bundled in the app: the same plus the
//!   Mac app's frameworks (`scripts/notices/mac-app.txt`, kept by hand), the app's Rust core and
//!   the npm packages in the Excalidraw and agent browser bundles.
//!
//! Rust crates come from `cargo about` (`about.toml`, `about.hbs`); npm packages from each
//! bundle's lockfile, installed with `npm ci --ignore-scripts` into `target/notices`. With
//! `--check` nothing is written; it fails if a file is out of date.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail, ensure};

use crate::{cargo, output, root, run, target_dir};

const RULE: &str =
    "================================================================================";

pub fn notices(check: bool) -> Result<()> {
    let root = root();
    let native = fs::read_to_string(root.join("scripts/notices/native.txt"))?;
    let mac_app = fs::read_to_string(root.join("scripts/notices/mac-app.txt"))?;
    let hostd = rust_crates("crates/hostd/Cargo.toml")?;
    let core = rust_crates("crates/apple-ffi/Cargo.toml")?;
    let excalidraw = npm_packages("excalidraw", false)?;
    let browser = npm_packages("agent-browser", true)?;

    let helper = [
        section("Native code linked into gudo-hostd", &native),
        section("Rust crates in gudo-hostd", &hostd),
    ]
    .concat();
    let app = [
        section("Native code linked into the app and its helpers", &native),
        section("Frameworks in the Mac app", &mac_app),
        section("Rust crates in the app (GudoCore)", &core),
        section("Rust crates in the bundled helpers (gudo-hostd)", &hostd),
        section("npm packages in the Excalidraw canvas bundle", &excalidraw),
        section("npm packages in the agent browser scripts", &browser),
    ]
    .concat();

    let header = |what: &str| {
        format!(
            "Third-party notices for {what}.\n\n\
             This file is generated by `cargo xtask notices`; do not edit it. Each section \
             lists licences with the components that use them.\n"
        )
    };
    let outputs = [
        (
            root.join("crates/hostd/THIRD_PARTY_NOTICES.txt"),
            header(brand::DAEMON_BIN) + &helper,
        ),
        (
            root.join("apple/App/Resources/THIRD_PARTY_NOTICES.txt"),
            header("the app") + &app,
        ),
    ];
    let mut stale = Vec::new();
    for (path, text) in outputs {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current == text {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
            eprintln!("wrote {}", path.display());
        }
    }
    if !stale.is_empty() {
        bail!(
            "out of date (run `cargo xtask notices`): {}",
            stale.join(", ")
        );
    }
    Ok(())
}

fn section(title: &str, body: &str) -> String {
    format!("\n{RULE}\n{title}\n{RULE}\n\n{}\n", body.trim())
}

/// Licence texts for the non-dev, non-build dependencies of one shipped crate.
fn rust_crates(manifest: &str) -> Result<String> {
    let root = root();
    output(
        cargo()
            .current_dir(&root)
            .args([
                "about",
                "generate",
                "--fail",
                "--locked",
                "-c",
                "about.toml",
                "-m",
            ])
            .arg(manifest)
            .arg("about.hbs"),
    )
    .context("cargo about (cargo install --locked cargo-about --features cli)")
}

/// Licence texts for the packages of one bundle in `apple/scripts/<name>`, grouped by text.
/// `dev` includes development dependencies (a bundle whose packages are all build inputs);
/// esbuild, the bundler, never is.
fn npm_packages(name: &str, dev: bool) -> Result<String> {
    let source = root().join("apple/scripts").join(name);
    let work = target_dir().join("notices").join(name);
    fs::create_dir_all(&work)?;
    for file in ["package.json", "package-lock.json"] {
        fs::copy(source.join(file), work.join(file))?;
    }
    run(std::process::Command::new("npm").current_dir(&work).args([
        "ci",
        "--ignore-scripts",
        "--no-audit",
        "--no-fund",
        "--silent",
    ]))?;

    let lock: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(work.join("package-lock.json"))?)?;
    let packages = lock["packages"]
        .as_object()
        .context("package-lock.json has no packages")?;
    let mut by_text: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (path, meta) in packages {
        let Some(package) = path
            .rsplit("node_modules/")
            .next()
            .filter(|_| !path.is_empty())
        else {
            continue;
        };
        if package == "esbuild" || package.starts_with("@esbuild/") || (!dev && meta["dev"] == true)
        {
            continue;
        }
        let version = meta["version"].as_str().unwrap_or("?");
        let licence = meta["license"].as_str().unwrap_or("see text");
        let text = licence_text(&work.join(path))
            .with_context(|| format!("{name}: no licence file in {path}"))?;
        by_text
            .entry(text)
            .or_default()
            .push(format!("  {package} {version} ({licence})"));
    }
    ensure!(!by_text.is_empty(), "{name}: no packages");
    let mut groups: Vec<(Vec<String>, String)> = by_text
        .into_iter()
        .map(|(text, mut users)| {
            users.sort();
            users.dedup();
            (users, text)
        })
        .collect();
    groups.sort();
    Ok(groups
        .into_iter()
        .map(|(users, text)| format!("{}\n\n{}\n", users.join("\n"), text.trim()))
        .collect::<Vec<_>>()
        .join(&format!("\n{}\n", "-".repeat(80))))
}

/// The package's own licence file. Packages that ship none (some publish only the SPDX
/// id) get the standard text for that id.
fn licence_text(dir: &Path) -> Result<String> {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .filter(|path| {
            let name = path
                .file_name()
                .and_then(|name| name.to_str())
                .unwrap_or_default()
                .to_ascii_lowercase();
            path.is_file()
                && (name.starts_with("license") || name.starts_with("licence") || name == "copying")
        })
        .collect();
    files.sort();
    if let Some(first) = files.first() {
        return Ok(fs::read_to_string(first)?);
    }
    let meta: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(dir.join("package.json"))?)?;
    let author = match &meta["author"] {
        serde_json::Value::String(name) => name.clone(),
        serde_json::Value::Object(person) => person
            .get("name")
            .and_then(|name| name.as_str())
            .unwrap_or_default()
            .to_owned(),
        _ => String::new(),
    };
    match meta["license"].as_str() {
        Some("MIT") => Ok(format!(
            "MIT License\n\nCopyright (c) {}\n\n{MIT}",
            if author.is_empty() {
                "its authors".into()
            } else {
                author
            }
        )),
        Some("ISC") => Ok(format!(
            "ISC License\n\nCopyright (c) {}\n\n{ISC}",
            if author.is_empty() {
                "its authors".into()
            } else {
                author
            }
        )),
        other => bail!("licence {other:?} without a licence file"),
    }
}

